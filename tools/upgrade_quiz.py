def mixed(lst, seed):  # 분류가 고르게 섞이도록 분류별로 돌아가며 꺼낸 순서
    by = defaultdict(list)
    for q in lst: by[q["category"]].append(q)
    r = random.Random(seed)
    for k in by: r.shuffle(by[k])
    out = []
    while any(by.values()):
        for k in CATS:
            if by[k]: out.append(by[k].pop())
    return out
